  SUBROUTINE imm2pres(rd_imm,rd_lat,rd_pres)
    !
    ! FHZ Mai 2008
    ! Calcul inverse en utilisant la formulation UNESCO de
    ! calcul de l immersion a partir de la pression
    !
    ! Methode:
    !     Pour une immersion, on cherche une pression.
    !     Or, comme on a une conversion pression vers immersion
    !     et que la pression est superieure a l immersion
    !     on va calculer toutes les pressions a partir de la
    !     valeur d immersion pour trouver la bonne valeur
    ! 
    ! Entree:
    !  rd_imm: immersion en metres
    !  rd_lat: latitude en degres
    ! Sortie:
    !  rd_pres: pression en decibar
    !
    IMPLICIT NONE
    REAL(KIND=8), INTENT(IN) :: rd_imm,rd_lat
    REAL(KIND=8), INTENT(OUT):: rd_pres
    REAL(KIND=8) :: rl_pres,rl_depth
    logical :: ll_test

    !* initialisation de la plage de valeur de scan en pression
    rl_pres = rd_imm
    ll_test = .true.

    !* on cherche la valeur d immersion la plus proche en augmentant la 
    !  pression de 1dbar a chaque fois
    do while ( ll_test )
       call pres2imm_UNESCO(rl_pres,rd_lat,rl_depth)
       if ( rl_depth > rd_imm ) ll_test = .false.
       rl_pres = rl_pres + 1.d0
    enddo
    rd_pres = rl_pres - 1.d0

    RETURN
  END SUBROUTINE imm2pres
