  REAL (KIND=8) FUNCTION hydro_tetai8 (xp8,xt8,xs8,xpr8)


    !* RECUP par FHZ aupres de CLS Mai 2008
    !
    !     creation : Decembre 89	auteur : D.Jacolot
    !     --------  				 ------
    !
    !     modification :	
    !     ------------	
    !     01. Correction xpr8	     14/6/91	  C.Lagadec
    !	  Prise en compte de la double precision
    !
    !     02. Correction t90	     07/07/92	  C.Lagadec
    !	  Prise en compte de la nouvelle echelle de temperature
    !
    !     03. Recuperation par FHZ modif des declarations en F90
    !
    !
    !     objet : Calcul de la temperature potentielle au niveau pr
    !     -----
    !
    !     description :
    !     -----------
    !	methode fofonoff, deep-sea research vol 24, 489-491, 1977
    !	calcul de gamma :
    !	formule de bryden, deep-sea research vol 20, 401-408, 1973
    !	valeurs de controle: p = 10**4 decibars
    !			     t = 40 degres
    !			     s = 40 nsu
    !			     pr = 0
    !				  teta = 36.89101
    !
    !	(ecrit a partir de tetai de hydrobib)
    !
    !     entree :
    !     ------
    !	 xp8	 : pression
    !	 xt8,xs8 : temperature (t90) et salinite
    !	 xpr8	 : pression de reference
    !
    !     sortie :
    !     ------
    !	 temperature potentielle (t90) au niveau pr en degres Celsius
    !
    !     sous-programmes appeles :
    !     -----------------------
    !-----------------------------------------------------------------
    !
    IMPLICIT NONE
    !
    REAL(kind=8),INTENT(in) :: xp8,xt8,xs8,xpr8

    REAL(kind=8),PARAMETER :: a000=.35803d-01, a001=.85258d-02, a002=-.68360d-04,&
         &  a003=.66228d-06, a010=.18932d-02, a011=-.42393d-04, a100=.18741d-04,&
         &  a101=-.67795d-06, a102=.87330d-08, a103=-.54481d-10, a110=-.11351d-06,&
         &  a111=.27759d-08, a200=-.46206d-09, a201= .18676d-10, a202=-.21687d-12

    INTEGER(kind=4)  :: i
    REAL(kind=8) :: p,t,s,pr,dp
    REAL(kind=8) :: t2,t3,p2,g,g1,g2,g3,g4,q2,q3
    REAL(kind=8) :: teta1,teta2,teta3,teta4

    !* initialisation
    p = xp8 
    t = xt8 * 1.00024

    s = xs8
    s = s - 35.d0

    pr = xpr8
    dp = pr - p
    i = 0

    ! commentaire FHZ: integration en pression de P a Pr par un Runge-Kutta
    ! de la fonction "adiabatic lapse rate" correspondant a la variation adiabatique
    ! de temperature par variation de pression (en deg. C / decibar )
10  t2 = t*t
    t3 = t2*t
    p2 = p*p
    g = a000 + a001*t + a002*t2 + a003*t3 + a010*s + a011*s*t  + a100*p +a101*p*t + &
         & a102*p*t2 + a103*p*t3 + a110*p*s + a111*p*s*t + a200*p2 + a201*p2*t + a202*p2*t2
    i = i + 1
    GOTO (1,2,3,4),i

1   g1 = dp*g*1.d-03
    teta1 = t + g1*.5d0
    p = p + dp*.5d0
    t = teta1
    GOTO 10

2   g2 = dp*g*1.d-03
    teta2 = teta1 + .292893218d0*(g2 - g1)
    t = teta2
    GOTO 10

3   g3 = dp*g*1.d-03
    q2 = .585786437d0*g2 + .121320343d0*g1
    teta3 = teta2 + 1.707106781d0*(g3 - q2)
    p = pr
    t = teta3
    GOTO 10

4   g4 = dp*g*1.d-03
    q3 = 3.414213562d0*g3 - 4.121320343d0*q2
    teta4 = teta3 + (g4 - q3*2.d0)/6.d0

    !commentaire FHZ: ceci est une difference avec la routine UNESCO:
    hydro_tetai8 = teta4 * 0.99976

    RETURN

  END FUNCTION hydro_tetai8

