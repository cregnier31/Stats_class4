  SUBROUTINE pres2imm_UNESCO(rd_pres,rd_phi,rd_depth)
    !
    ! FHZ Mai 2008
    ! 
    ! Convertir des pressions (decibar) en immersion (metres) a
    ! partir de la formulation UNESCO (routine DEPTH(P,LAT) ):
    ! Unesco technical papers in marine science N. 44 qui se
    ! sert de la formulation Saunders and Fofonoff's
    ! Deep-Sea Research, 1976, 23, 109-111
    !
    ! Checking value: DEPTH=9712.653m for P=10.e4 Decibar, PHI=30. deg.
    !
    ! Entree:
    !    rd_pres: pression (decibar)
    !    rd_phi: latitude (degres)
    ! Sortie:
    !    rd_depth: immersion (m)

    IMPLICIT NONE
    REAL(KIND=8), INTENT(IN) :: rd_pres,rd_phi
    REAL(KIND=8), INTENT(OUT):: rd_depth
    REAL(kind=8)  :: p,x,gr,depth

    p = rd_pres
    x = SIN(rd_phi/57.29578)
    x = x * x
    gr = 9.780318d0 * (1.d0 + (5.2788d-3 + 2.36d-5 * x) * x)
    gr = gr + 1.092d-6 * p

    depth = (((-1.82d-15 * p + 2.279d-10) * p - 2.2512d-5) * p + 9.72659d0) * p
    depth = depth / gr

    rd_depth = depth

    RETURN
  END SUBROUTINE pres2imm_UNESCO
 
